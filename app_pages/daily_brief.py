"""Daily Brief page — AI-generated executive briefing."""
from __future__ import annotations

import datetime
import streamlit as st


def render():
    st.markdown("## 📋 AI Daily Brief")
    st.markdown("*Your personalised executive intelligence briefing*")

    # Controls
    ctrl_col1, ctrl_col2, ctrl_col3, ctrl_col4 = st.columns([2, 1, 1, 1])
    with ctrl_col1:
        selected_date = st.date_input(
            "Brief Date", value=datetime.date.today(), key="brief_date"
        )
    with ctrl_col2:
        st.write("")
        regenerate = st.button("🔄 Generate Brief", type="primary")
    with ctrl_col3:
        st.write("")
        export_md = st.button("📥 Export MD")
    with ctrl_col4:
        st.write("")
        export_txt = st.button("📄 Export TXT")

    # Get or generate brief
    bedrock = st.session_state.get("bedrock_service")
    brief_key = f"brief_{selected_date}"

    if regenerate or brief_key not in st.session_state:
        with st.spinner("🤖 Generating your executive brief with AI..."):
            import time
            time.sleep(0.8)
            brief = bedrock.generate_daily_brief({"date": str(selected_date)})
            st.session_state[brief_key] = brief
            st.success("Brief generated!")

    brief = st.session_state.get(brief_key, {})

    if export_md and brief:
        md_content = _brief_to_markdown(brief, selected_date)
        st.download_button(
            "Download .md", md_content, f"brief_{selected_date}.md", "text/markdown"
        )

    if export_txt and brief:
        txt_content = _brief_to_text(brief, selected_date)
        st.download_button(
            "Download .txt", txt_content, f"brief_{selected_date}.txt", "text/plain"
        )

    if not brief:
        st.info("Click **Generate Brief** to create your AI briefing.")
        return

    # ── Render Brief Sections ──────────────────────────────────────────────────

    st.markdown("---")

    # Executive Summary
    st.html(
        f"""
        <div style="background:linear-gradient(135deg,#1e293b,#0f172a);
                    border:1px solid #334155; border-left:5px solid #6366f1;
                    border-radius:10px; padding:18px 20px; margin-bottom:16px;">
            <div style="font-size:0.75rem; color:#818cf8; font-weight:600; text-transform:uppercase;
                        letter-spacing:1px; margin-bottom:8px;">
                &#129504; Executive Summary
            </div>
            <div style="font-size:0.95rem; color:#e2e8f0; line-height:1.7;">
                {brief.get('executive_summary', 'No summary generated.')}
            </div>
            <div style="font-size:0.72rem; color:#475569; margin-top:10px;">
                &#128197; Brief for {selected_date.strftime('%A, %B %d, %Y')} &middot; Generated by Claude AI
            </div>
        </div>
        """
    )

    # Metrics snapshot
    metrics = brief.get("metrics_snapshot", {})
    if metrics:
        m_cols = st.columns(6)
        metric_items = [
            ("📧", "Emails", metrics.get("total_emails", 0)),
            ("🚨", "Critical", metrics.get("critical_emails", 0)),
            ("✅", "Tasks", metrics.get("pending_tasks", 0)),
            ("⛔", "Overdue", metrics.get("tasks_overdue", 0)),
            ("📅", "Meetings", metrics.get("meetings_this_week", 0)),
            ("⚡", "AI Saved", f"{metrics.get('estimated_time_saved_hours', 0)}h"),
        ]
        for col, (icon, label, val) in zip(m_cols, metric_items):
            with col:
                st.html(
                    f'<div style="background:#0f172a; border:1px solid #1e293b; border-radius:6px; '
                    f'padding:8px; text-align:center;">'
                    f'<div style="font-size:1.1rem;">{icon}</div>'
                    f'<div style="font-size:1.1rem; font-weight:700; color:#f1f5f9;">{val}</div>'
                    f'<div style="font-size:0.65rem; color:#64748b;">{label}</div></div>'
                )

    st.write("")

    # Two-column layout for most sections
    left_col, right_col = st.columns(2)

    with left_col:
        # Urgent Items
        urgent = brief.get("urgent_items", [])
        if urgent:
            with st.expander(f"🚨 URGENT — {len(urgent)} Critical Item(s)", expanded=True):
                for item in urgent:
                    severity_color = "#dc2626" if item.get("severity") == "Critical" else "#f97316"
                    st.html(
                        f"""
                        <div style="background:rgba(220,38,38,0.08); border:1px solid rgba(220,38,38,0.25);
                                    border-radius:6px; padding:10px 12px; margin-bottom:8px;">
                            <div style="font-weight:600; color:{severity_color}; font-size:0.85rem;">
                                &#9889; {item.get('title','')}
                            </div>
                            <div style="font-size:0.78rem; color:#cbd5e1; margin-top:4px;">
                                {item.get('description','')}
                            </div>
                            <div style="font-size:0.73rem; color:#94a3b8; margin-top:6px;">
                                <strong>Action:</strong> {item.get('action','')}
                            </div>
                            <div style="font-size:0.70rem; color:#f97316; margin-top:2px;">
                                &#9200; Deadline: {item.get('deadline','')}
                            </div>
                        </div>
                        """
                    )

        # Action Required
        actions = brief.get("action_required", [])
        if actions:
            with st.expander(f"⚡ ACTION REQUIRED — {len(actions)} item(s)", expanded=True):
                for item in actions:
                    st.html(
                        f"""
                        <div style="background:rgba(249,115,22,0.08); border:1px solid rgba(249,115,22,0.25);
                                    border-radius:6px; padding:10px 12px; margin-bottom:6px;">
                            <div style="font-weight:600; color:#fb923c; font-size:0.83rem;">
                                {item.get('title','')}
                            </div>
                            <div style="font-size:0.75rem; color:#cbd5e1; margin-top:4px;">
                                {item.get('description','')}
                            </div>
                            <div style="font-size:0.70rem; color:#f59e0b; margin-top:4px;">
                                &#128197; Deadline: {item.get('deadline','')}
                            </div>
                        </div>
                        """
                    )

        # Risks
        risks = brief.get("risks", [])
        if risks:
            with st.expander(f"⚠️ RISKS — {len(risks)} identified", expanded=False):
                for risk in risks:
                    level = risk.get("level", "Medium")
                    rc = {"Critical": "#dc2626", "High": "#f97316", "Medium": "#f59e0b", "Low": "#22c55e"}.get(level, "#6b7280")
                    st.html(
                        f"""
                        <div style="border-left:3px solid {rc};
                                    border-radius:4px; padding:8px 10px; margin-bottom:6px; background:rgba(0,0,0,0.2);">
                            <span style="color:{rc}; font-weight:600; font-size:0.8rem;">[{level}]</span>
                            <span style="color:#e2e8f0; font-size:0.8rem;"> {risk.get('risk','')}</span>
                            <div style="font-size:0.72rem; color:#94a3b8; margin-top:3px;">
                                &#128161; {risk.get('mitigation','')}
                            </div>
                        </div>
                        """
                    )

    with right_col:
        # Today's Deadlines
        deadlines_today = brief.get("deadlines_today", [])
        if deadlines_today:
            with st.expander(f"⏰ TODAY'S DEADLINES — {len(deadlines_today)}", expanded=True):
                for d in deadlines_today:
                    st.html(
                        f'<div style="background:rgba(220,38,38,0.08); border:1px solid rgba(220,38,38,0.25); '
                        f'border-radius:4px; padding:6px 10px; margin-bottom:4px; font-size:0.8rem;">'
                        f'&#128308; <strong style="color:#fca5a5;">{d.get("item","")}</strong> &mdash; '
                        f'<span style="color:#94a3b8;">{d.get("time","")}</span></div>'
                    )

        # Week's Deadlines
        deadlines_week = brief.get("deadlines_this_week", [])
        if deadlines_week:
            with st.expander(f"📅 WEEK'S DEADLINES — {len(deadlines_week)}", expanded=True):
                for d in deadlines_week:
                    st.html(
                        f'<div style="background:rgba(245,158,11,0.08); border:1px solid rgba(245,158,11,0.25); '
                        f'border-radius:4px; padding:6px 10px; margin-bottom:4px; font-size:0.8rem;">'
                        f'&#128993; <strong style="color:#fde68a;">{d.get("item","")}</strong> &mdash; '
                        f'<span style="color:#94a3b8;">{d.get("date","")}</span></div>'
                    )

        # Today's Meetings
        meetings_today = brief.get("meetings_today", [])
        if meetings_today:
            with st.expander(f"📅 TODAY'S MEETINGS — {len(meetings_today)}", expanded=True):
                for m in meetings_today:
                    st.html(
                        f"""
                        <div style="background:rgba(16,185,129,0.08); border:1px solid rgba(16,185,129,0.25);
                                    border-radius:4px; padding:6px 10px; margin-bottom:4px; font-size:0.8rem;">
                            &#129309; <strong style="color:#6ee7b7;">{m.get('title','')}</strong><br/>
                            <span style="color:#94a3b8; font-size:0.73rem;">
                                {m.get('time','')} &middot; {m.get('location','')} &middot; {m.get('attendees',0)} attendees
                            </span>
                        </div>
                        """
                    )

        # This Week's Meetings
        meetings_week = brief.get("meetings_this_week", [])
        if meetings_week:
            with st.expander(f"📅 WEEK'S MEETINGS — {len(meetings_week)}", expanded=False):
                for m in meetings_week:
                    note_html = (
                        f'<span style="color:#f59e0b;"> &#9888; {m.get("note","")}</span>'
                        if m.get("note") else ""
                    )
                    st.html(
                        f'<div style="background:rgba(99,102,241,0.08); border:1px solid rgba(99,102,241,0.25); '
                        f'border-radius:4px; padding:6px 10px; margin-bottom:4px; font-size:0.8rem;">'
                        f'&#128197; <strong style="color:#a5b4fc;">{m.get("title","")}</strong><br/>'
                        f'<span style="color:#94a3b8; font-size:0.72rem;">{m.get("date","")} at {m.get("time","")}'
                        f'{note_html}</span></div>'
                    )

    # Recommendations
    recs = brief.get("recommendations", [])
    if recs:
        st.markdown("---")
        with st.expander("💡 AI RECOMMENDATIONS", expanded=True):
            for i, rec in enumerate(recs, 1):
                st.html(
                    f'<div style="background:rgba(99,102,241,0.08); border:1px solid rgba(99,102,241,0.25); '
                    f'border-radius:6px; padding:8px 12px; margin-bottom:6px; font-size:0.82rem; color:#e2e8f0;">'
                    f'<span style="color:#818cf8; font-weight:700;">{i}.</span> {rec}</div>'
                )


def _brief_to_markdown(brief: dict, date: datetime.date) -> str:
    lines = [f"# Executive Daily Brief — {date.strftime('%B %d, %Y')}", ""]
    lines += ["## Executive Summary", brief.get("executive_summary", ""), ""]

    if brief.get("urgent_items"):
        lines += ["## 🚨 Urgent Items"]
        for item in brief["urgent_items"]:
            lines += [f"### {item.get('title','')}", item.get("description",""),
                      f"**Action:** {item.get('action','')}", f"**Deadline:** {item.get('deadline','')}", ""]

    if brief.get("risks"):
        lines += ["## ⚠️ Risks"]
        for r in brief["risks"]:
            lines += [f"- **[{r.get('level','')}]** {r.get('risk','')} — {r.get('mitigation','')}"]
        lines.append("")

    if brief.get("recommendations"):
        lines += ["## 💡 Recommendations"]
        for i, r in enumerate(brief["recommendations"], 1):
            lines.append(f"{i}. {r}")

    return "\n".join(lines)


def _brief_to_text(brief: dict, date: datetime.date) -> str:
    return _brief_to_markdown(brief, date).replace("#", "").replace("**", "")
